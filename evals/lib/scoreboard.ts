import type { EvalRecord } from "./types";

export type RunSummary = {
  at: string;
  fixtures: "dev" | "dev+holdout";
  fresh: boolean;
  spend_usd: number;
  model_calls: number;
  cached_calls: number;
  results: Record<string, EvalRecord["status"]>;
};

/** Consecutive full-run passes, newest first. A gate counts at two. */
export function passStreak(history: RunSummary[], id: string): number {
  let streak = 0;
  for (let i = history.length - 1; i >= 0; i--) {
    if (history[i]!.results[id] !== "pass") break;
    streak += 1;
  }
  return streak;
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

export function renderScoreboard(records: EvalRecord[], history: RunSummary[]): string {
  const run = history[history.length - 1]!;
  const gates = records.filter((r) => r.kind === "gate");
  const passed = gates.filter((r) => r.status === "pass").length;
  const lines = [
    "# Eval scoreboard",
    "",
    "Generated by `npm run eval:all`. Do not edit by hand.",
    "",
    `- Run: ${run.at}`,
    `- Fixtures: ${run.fixtures}`,
    `- Fresh model calls: ${run.fresh ? "yes" : "no (cache allowed)"}`,
    `- Spend this run: $${run.spend_usd.toFixed(2)} over ${run.model_calls} model calls (${run.cached_calls} from cache)`,
    `- Gates passing: ${passed}/${gates.length}`,
    "",
    "A gate counts only when it has passed on two full runs in a row (streak of 2 or more).",
    "",
    "| Eval | Kind | Status | Streak | Measures | Why it is not passing |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const r of records) {
    const measures = r.measures.map((m) => `${m.pass ? "ok" : "MISS"} ${m.name}: ${m.value} (bar: ${m.bar})`).join("; ");
    lines.push(
      `| **${r.id}** ${cell(r.title)} | ${r.kind} | ${r.status.toUpperCase()} | ${passStreak(history, r.id)} | ${cell(measures) || "not measured"} | ${cell(r.reason ?? "")} |`,
    );
  }
  const withFailures = records.filter((r) => r.failures.length > 0);
  if (withFailures.length > 0) {
    lines.push("", "## Failing cases", "");
    for (const r of withFailures) {
      lines.push(`### ${r.id} ${r.title}`, "");
      for (const failure of r.failures.slice(0, 25)) lines.push(`- ${failure}`);
      if (r.failures.length > 25) lines.push(`- ... and ${r.failures.length - 25} more`);
      lines.push("");
    }
  }
  return lines.join("\n").trimEnd() + "\n";
}
